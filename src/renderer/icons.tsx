// UI icons.
//
// These replaced emoji, which had been standing in as icons all over the
// dashboard. Emoji were never really icons: every OS draws its own, so the set
// was Apple's on a Mac and Microsoft's on Windows, they carry their own colour
// and so ignore the surrounding text colour, they sit on the text baseline
// rather than optically centred, and several (⚙️, 🏷️, 🎙️) render as flat
// monochrome glyphs on some platforms and full-colour stickers on others. A
// toolbar built from them looks different on every machine.
//
// The geometry follows Lucide's conventions — 24x24 box, 2px grid, round caps
// and joins, stroke rather than fill — because it is the house style most
// modern dashboards read as "normal", and consistency between icons matters
// more than any individual shape. They are hand-inlined rather than pulled from
// the package for the same reason the router is twenty lines: this is a fixed
// set that never changes at runtime, and a dependency would ship a tree-shaking
// problem to solve a copy-paste one.
//
// Every icon inherits `currentColor` and sizes off `className`, so one lives
// correctly in a muted sidebar, a red destructive button and a brand-coloured
// header without variants. Brand marks (Twitch, Kick, YouTube, Rumble) stay in
// ui.tsx — those are logos with fixed shapes, not part of this system.
import type { CSSProperties, ReactNode } from "react";

function Icon({
  className = "h-4 w-4",
  style,
  strokeWidth = 2,
  children,
}: {
  className?: string;
  style?: CSSProperties;
  strokeWidth?: number;
  children: ReactNode;
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden
    >
      {children}
    </svg>
  );
}

type P = { className?: string; style?: CSSProperties; strokeWidth?: number };

